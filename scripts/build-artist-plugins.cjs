'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');

const marketRoot = path.resolve(__dirname, '..');
const panelRoot = path.resolve(process.env.RHINE_PANEL_ROOT || path.join(marketRoot, '..', 'RhineMusicPanel'));
const panelRequire = createRequire(path.join(panelRoot, 'package.json'));
const esbuild = panelRequire('esbuild');
const mobilePlugin = require(path.join(panelRoot, 'scripts', 'mobile-bridge-plugin.cjs'));
process.env.RHINE_PANEL_ROOT = panelRoot;
const baselineHashes = {
    netease: 'b61deaabf9619e794be9867bda25db39b73fa3c06608ed4f13e2cfab269df094',
    qq: '88c1474a2bdf525073c732eb918c1386ac767278175d3ad20a0ac8e79b797ac0',
};

/** 使用已锁定依赖构建市场插件，并保留可重建的兼容基底。 */
async function build() {
    const upstreamPath = path.join(panelRoot, 'MusicBridge', 'node_modules',
        '@neteasecloudmusicapienhanced', 'api', 'package.json');
    const upstream = JSON.parse(fs.readFileSync(upstreamPath, 'utf8'));
    if (upstream.version !== '4.41.1') {
        throw new Error('上游 API 版本与插件锁定版本不一致');
    }
    for (const id of ['netease', 'qq']) {
        const source = path.join(marketRoot, 'sources', id);
        const directory = path.join(marketRoot, 'plugins', id);
        const outfile = path.join(directory, 'plugin.cjs');
        const baseline = fs.readFileSync(path.join(source, 'legacy.cjs'));
        const baselineHash = crypto.createHash('sha256').update(baseline).digest('hex');
        if (baselineHash !== baselineHashes[id]) {
            throw new Error('兼容基底校验失败：' + id);
        }
        const pluginBuild = require(path.join(source, 'build.cjs'));
        await esbuild.build({
            entryPoints: [path.join(source, 'index.mjs')],
            outfile,
            bundle: true,
            platform: 'node',
            format: 'cjs',
            target: 'node18',
            logLevel: 'warning',
            logOverride: { 'require-resolve-not-external': 'silent' },
            plugins: [mobilePlugin('ios-web-apis.cjs'), ...pluginBuild.plugins],
            banner: { js: '// Generated by scripts/build-artist-plugins.cjs; do not edit.' },
        });
        const manifestPath = path.join(directory, 'manifest.json');
        const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
        const bundle = fs.readFileSync(outfile);
        manifest.entry = {
            file: 'plugin.cjs',
            sha256: crypto.createHash('sha256').update(bundle).digest('hex'),
            size: bundle.length,
        };
        delete manifest.runtime.sourceEntry;
        fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 4) + '\n');
        console.log('插件已打包：' + id);
    }
}

build().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
});
